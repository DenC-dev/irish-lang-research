#!/usr/bin/env python3
"""Subordinate-clause density in the two Irish UD treebanks.

Motivated by Ó Broin's radio study (Gaeltacht newsreaders about 15 subordinate
clauses per 10 sentences, urban 6 to 8). This applies the same idea to written
data. Genre differs between the treebanks, so the contrast is edited prose
versus tweets and says nothing about speaker groups.

    python3 -I scripts/clause_density.py --idt external/UD_Irish-IDT \
        --twittirish external/UD_Irish-TwittIrish --out results
"""
import argparse
import collections
import glob
import json
import os

SUBORD = ("ccomp", "xcomp", "advcl", "acl", "csubj")


def scan(folder):
    c = collections.Counter()
    by_rel = collections.Counter()
    n_sub = 0
    for f in sorted(glob.glob(os.path.join(folder, "*.conllu"))):
        with open(f, encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("#"):
                    continue
                if not line.strip():
                    if c["_open"]:
                        c["sentences"] += 1
                        c["with_sub"] += n_sub > 0
                        c["_open"] = 0
                    n_sub = 0
                    continue
                col = line.rstrip("\n").split("\t")
                if len(col) != 10 or not col[0].isdigit():
                    continue
                c["_open"] = 1
                c["tokens"] += 1
                base = col[7].split(":")[0]
                if base in SUBORD:
                    c["subord"] += 1
                    n_sub += 1
                    by_rel[col[7]] += 1
                    if col[7] != "xcomp:pred":
                        c["strict"] += 1
                    if col[7] == "acl:relcl":
                        c["relcl"] += 1
    if c["_open"]:
        c["sentences"] += 1
        c["with_sub"] += n_sub > 0
    return {
        "sentences": c["sentences"],
        "tokens": c["tokens"],
        "subordinate_clauses": c["subord"],
        "per_10_sentences": round(10 * c["subord"] / c["sentences"], 2),
        "per_100_tokens": round(100 * c["subord"] / c["tokens"], 2),
        "strict_excl_xcomp_pred": c["strict"],
        "strict_per_10_sentences": round(10 * c["strict"] / c["sentences"], 2),
        "strict_per_100_tokens": round(100 * c["strict"] / c["tokens"], 2),
        "relative_clauses_per_100_tokens": round(100 * c["relcl"] / c["tokens"], 2),
        "sentences_with_any_pct": round(100 * c["with_sub"] / c["sentences"], 1),
        "by_relation": dict(by_rel.most_common()),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--idt", required=True)
    ap.add_argument("--twittirish", required=True)
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    res = {"IDT": scan(a.idt), "TwittIrish": scan(a.twittirish)}
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "clause_density.json"), "w", encoding="utf-8") as fh:
        json.dump(res, fh, ensure_ascii=False, indent=2)
    i, t = res["IDT"], res["TwittIrish"]
    md = "\n".join([
        "# Subordinate-clause density: edited Irish vs Irish tweets", "",
        "Generated by `scripts/clause_density.py`. Counts dependency relations",
        "ccomp, xcomp, advcl, acl (incl. acl:relcl) and csubj. Genre differs, so this",
        "is a register contrast only.", "",
        "| Measure | UD Irish-IDT | UD Irish-TwittIrish |", "|---|---:|---:|",
        f"| Sentences / tweets | {i['sentences']} | {t['sentences']} |",
        f"| Subordinate clauses | {i['subordinate_clauses']} | {t['subordinate_clauses']} |",
        f"| Per 10 sentences / tweets | {i['per_10_sentences']} | {t['per_10_sentences']} |",
        f"| Per 100 tokens | {i['per_100_tokens']} | {t['per_100_tokens']} |",
        f"| Excluding xcomp:pred (predicates of the verb bí), per 10 | {i['strict_per_10_sentences']} | {t['strict_per_10_sentences']} |",
        f"| Excluding xcomp:pred, per 100 tokens | {i['strict_per_100_tokens']} | {t['strict_per_100_tokens']} |",
        f"| Relative clauses (acl:relcl) per 100 tokens | {i['relative_clauses_per_100_tokens']} | {t['relative_clauses_per_100_tokens']} |",
        f"| Sentences / tweets with at least one (%) | {i['sentences_with_any_pct']} | {t['sentences_with_any_pct']} |",
        "", f"IDT by relation: {i['by_relation']}", "", f"TwittIrish by relation: {t['by_relation']}", ""])
    with open(os.path.join(a.out, "clause_density.md"), "w", encoding="utf-8") as fh:
        fh.write(md)
    print(md)


if __name__ == "__main__":
    main()
